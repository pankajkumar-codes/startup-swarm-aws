#!/usr/bin/env python3
"""Stage startup-swarm into an AgentCore CLI project for one stage (beta or prod).

What it does:
1. Reads the CDK outputs file (``cdk deploy --outputs-file ...``) for the stage's S3
   bucket, DynamoDB table and AgentCore execution role.
2. Copies the installed ``startup_swarm`` and ``startup_swarm_aws`` packages, your
   config.yaml and the entrypoint (as main.py) into <project-dir>/app/startup_swarm_<stage>/,
   with a pyproject.toml listing the runtime dependencies.
3. Adds or updates the runtime "startup_swarm_<stage>" in agentcore/agentcore.json, using
   the CDK role (executionRoleArn) and passing the stage settings as envVars.

Then run ``agentcore deploy`` inside <project-dir>. See README "Hosted mode on AgentCore".

Usage:
  python scripts/prepare_agentcore.py --stage beta --project-dir ../SwarmRuntime \\
      --outputs infrastructure/cdk-outputs-beta.json [--config config.yaml]
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGES = ["startup_swarm", "startup_swarm_aws"]
PYPROJECT = """\
[project]
name = "startup-swarm-runtime"
version = "0.1.0"
requires-python = ">=3.11"
dependencies = [
    "bedrock-agentcore",
    "boto3>=1.40",
    "pydantic>=2.6",
    "pyyaml>=6.0",
]
"""


def stack_name(stage: str) -> str:
    return f"StartupSwarm-{stage.capitalize()}"


def read_outputs(path: str, stage: str) -> dict:
    with open(path, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    stack = stack_name(stage)
    if stack not in data:
        raise SystemExit(f"{stack} not found in {path}. Deploy it with cdk first.")
    out = data[stack]
    for key in ("ArtifactBucketName", "StateTableName", "AgentRuntimeRoleArn"):
        if key not in out:
            raise SystemExit(f"Output {key} missing from {stack} in {path}")
    return out


def package_dir(name: str) -> str:
    return os.path.dirname(importlib.import_module(name).__file__)


def stage_code(dest: str, config_path: str) -> None:
    if os.path.exists(dest):
        shutil.rmtree(dest)
    os.makedirs(dest)
    for pkg in PACKAGES:
        shutil.copytree(package_dir(pkg), os.path.join(dest, pkg), ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy(config_path, os.path.join(dest, "config.yaml"))
    with open(os.path.join(dest, "main.py"), "w", encoding="utf-8") as fh:
        fh.write(
            '"""AgentCore entrypoint (generated by prepare_agentcore.py)."""\n'
            "import os\n\n"
            'os.environ.setdefault("SWARM_CONFIG", os.path.join(os.path.dirname(__file__), "config.yaml"))\n\n'
            "from startup_swarm_aws.agentcore_main import app  # noqa: E402,F401\n\n"
            'if __name__ == "__main__":\n'
            "    app.run()\n"
        )
    with open(os.path.join(dest, "pyproject.toml"), "w", encoding="utf-8") as fh:
        fh.write(PYPROJECT)


def upsert_runtime(spec_path: str, entry: dict) -> None:
    with open(spec_path, "r", encoding="utf-8") as fh:
        spec = json.load(fh)
    runtimes = spec.setdefault("runtimes", [])
    for i, rt in enumerate(runtimes):
        if rt.get("name") == entry["name"]:
            runtimes[i] = {**rt, **entry}
            break
    else:
        runtimes.append(entry)
    with open(spec_path, "w", encoding="utf-8") as fh:
        json.dump(spec, fh, indent=2)
        fh.write("\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=["beta", "prod"], required=True)
    ap.add_argument("--project-dir", required=True, help="Folder created by `agentcore create`")
    ap.add_argument("--outputs", required=True, help="CDK outputs JSON file")
    ap.add_argument("--config", default=os.path.join(REPO, "config.yaml"), help="config.yaml to ship")
    ap.add_argument("--region", default=os.environ.get("AWS_REGION", "us-east-1"))
    args = ap.parse_args()

    spec_path = os.path.join(args.project_dir, "agentcore", "agentcore.json")
    if not os.path.exists(spec_path):
        print(f"{spec_path} not found. Create it first: agentcore create --name SwarmRuntime", file=sys.stderr)
        return 1

    outputs = read_outputs(args.outputs, args.stage)
    name = f"startup_swarm_{args.stage}"
    code_rel = f"app/{name}/"
    stage_code(os.path.join(args.project_dir, code_rel), args.config)
    upsert_runtime(
        spec_path,
        {
            "name": name,
            "build": "CodeZip",
            "entrypoint": "main.py",
            "codeLocation": code_rel,
            "runtimeVersion": "PYTHON_3_12",
            "networkMode": "PUBLIC",
            "executionRoleArn": outputs["AgentRuntimeRoleArn"],
            "envVars": [
                {"name": "STAGE", "value": args.stage},
                {"name": "SWARM_REGION", "value": args.region},
                {"name": "SWARM_PROVIDER", "value": "bedrock"},
                {"name": "SWARM_BACKEND", "value": "aws"},
                {"name": "S3_ARTIFACT_BUCKET", "value": outputs["ArtifactBucketName"]},
                {"name": "DYNAMODB_STATE_TABLE", "value": outputs["StateTableName"]},
            ],
        },
    )
    print(f"Runtime '{name}' staged in {args.project_dir}. Next:")
    print(f"  cd {args.project_dir} && agentcore validate && agentcore deploy")
    print(f'  agentcore invoke --runtime {name} --payload \'{{"action": "status", "project": "demo"}}\'')
    return 0


if __name__ == "__main__":
    sys.exit(main())
